def _texts(value: object, field: str | None = None):
    """Every `title` and `body` string in a tool call's arguments, at any depth."""
    if isinstance(value, dict):
        for key, item in value.items():
            yield from _texts(item, key)
    elif isinstance(value, list):
        for item in value:
            yield from _texts(item, field)
    elif isinstance(value, str) and field in TEXT_FIELDS:
        yield field, value


def _tokens(command: str) -> list[str]:
    import shlex

    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
        lexer.whitespace_split = True
        lexer.commenters = ""  # sh keeps a mid-word "#"; a stray one only adds words, which refuse
        return list(lexer)
    except ValueError:  # unbalanced quotes: the plain words still name the files
        return command.split()


# The word after `<<` or `<<-` that starts a here-document: quoted, or bare after an optional
# backslash. In arithmetic (`$((1 << 20))`, `((x << y))`), `<<` is a shift and opens none.
HEREDOC_WORD = re.compile(r"(-?)[ \t]*(?:'([^'\n]*)'|\"([^\"\n]*)\"|\\?([\w.-]+))")
PAREN_END = re.compile(r"[ \t]*\)")  # what follows a here-document's word on an `EOF)` line
WORD_START = " \t\n;&|()<>"  # a `#` first or after one of these starts a comment
UNQUOTE = str.maketrans("", "", "'\"\\")


def _literal(text: str) -> str:
    """`text` as one single-quoted shell word."""
    return "'" + text.replace("'", "'\\''") + "'"


class _Input:
    """Where bash reads on past a newline. It takes a here-document's text from its input, the lines after
    the one it reads: `stream` is where the next line that no here-document has taken starts. After an
    `EOF)` end it pushes the rest of that line back and reads it first: `links` maps the newline that ends
    such a rest to where reading goes on (the next rest, or the rest of the line a substitution closed on)."""

    def __init__(self) -> None:
        self.stream = 0
        self.links: dict[int, int] = {}

    def after(self, newline: int) -> int:
        """Where reading goes on past the newline at `newline`."""
        return self.links.get(newline, max(newline + 1, self.stream))


def _script(command: str) -> str:
    """The command rewritten for a plain word splitter, as the shell reads it: each quoted string one
    single-quoted word, backslash-newline continuations joined, the quotes, backquotes and backslashes
    in a comment escaped (its words stay), each here-document's `<<WORD` dropped and its text too once
    its end comes, and the text of each command substitution, `$(...)` or backquoted, quoted or not,
    added as lines of its own (in the line, a `$(...)` reads as `$()`)."""
    extra: list[str] = []
    try:  # every line, the last too, ends with a newline
        text = _scan(command if command.endswith("\n") else command + "\n", 0, "", extra, _Input())[0]
    except RecursionError:  # substitutions nested past Python's limit: read the line as written
        return command
    return "\n".join([text, *extra])


def _scan(
    command: str, i: int, closer: str, extra: list[str], read: _Input, comsub: bool = False,
    arith: bool = False, ends: list[tuple[str, bool, bool]] | None = None,
) -> tuple[str, int]:
    """The commands from `i` up to `closer` (`)` for a subshell or a substitution, "" for the end);
    `comsub` when they sit inside a `$(...)`, `<(...)` or `>(...)`, at any depth, and `arith` inside
    arithmetic. `ends` holds the here-documents (word, <<-, opened inside a substitution) whose text
    comes when the line ends, shared with a subshell, which bash reads with the same parser; `read` says
    where reading goes on past each newline."""
    out: list[str] = []
    ends = [] if ends is None else ends
    while i < len(command):
        char = command[i]
        if closer and char == closer:
            return "".join(out), i + 1
        if char == "\\":
            if command[i + 1:i + 2] == "\n":  # a backslash-newline joins the line to the next one bash reads
                i = read.after(i + 1)
            else:  # an escape stays
                out.append(command[i:i + 2])
                i += 2
        elif char in "'\"":
            kind = char
            if _dollars(out) % 2:  # $'...', which reads escapes, or $"..."
                out.pop()
                kind = "$'" if char == "'" else char
            text, i = _quoted(command, i + 1, kind, extra, read)
            out.append(_literal(text))
        elif char == "`":
            text, i = _backquoted(command, i + 1, read)
            extra.append(_script(text))
            out.append(_literal(text))
        elif command.startswith("$(", i):
            text, i = _substitution(command, i + 2, extra, read, command.startswith("$((", i))
            extra.append(text)
            out.append("'$()'")  # its text is read on lines of its own
        elif char == "(" and not arith and out[-1:] in (["<"], [">"]):  # a process substitution
            text, i = _substitution(command, i + 1, extra, read)
            out.append("(" + text + ")")
        elif char == "(":
            if command.startswith("((", i):  # arithmetic, read as one: no here-document opens or is read in it
                text, i = _scan(command, i + 1, ")", extra, read, comsub, True)
            else:  # a subshell
                text, i = _scan(command, i + 1, ")", extra, read, comsub, arith, ends)
            out.append("(" + text + ")")
        elif char == "#" and (not out or (out[-1][-1] in WORD_START and out[-1][0] != "\\")):  # `a\ #` is one word
            end = command.find("\n", i)
            end = len(command) if end < 0 else end
            out.append(re.sub(r"(['\"\\\\`])", r"\\\1", command[i:end]))  # its quotes start nothing
            i = end
        elif command.startswith("<<<", i):
            out.append("<<<")
            i += 3
        elif not arith and command.startswith("<<", i) and (heredoc := HEREDOC_WORD.match(command, i + 2)):
            word = next(word for word in heredoc.groups()[1:] if word is not None)
            ends.append((word, heredoc.group(1) == "-", comsub))
            out.append(" ")
            i = heredoc.end()
        elif char == "\n":
            out.append("\n")
            i = read.after(i)
            # The line's here-documents take their text from the input once reading goes on at a line's
            # start: past the rest of an `EOF)` line bash pushed back, which it reads first.
            if ends and command[i - 1:i] == "\n":
                end, pushed = _gather(command, i, ends)
                ends[:] = []  # in place: a subshell shares them
                read.stream = max(read.stream, end)
                i = _push_back(pushed, read, None) if pushed else end
        else:
            out.append(char)
            i += 1
    return "".join(out), i


def _substitution(command: str, i: int, extra: list[str], read: _Input, arith: bool = False) -> tuple[str, int]:
    """The commands of a `$(...)`, `<(...)` or `>(...)` (`arith` for `$((...))`) from `i` up to its `)`, and
    where reading goes on. Bash reads the text of a here-document it leaves waiting at once, from its
    input, and then the rest of any `EOF)` line that text ends at, before the rest of the line it closed on."""
    ends: list[tuple[str, bool, bool]] = []
    text, i = _scan(command, i, ")", extra, read, True, arith, ends)
    if ends:
        end, pushed = _gather(command, max(command.find("\n", i) + 1, read.stream), ends)
        read.stream = max(read.stream, end)
        if pushed:
            i = _push_back(pushed, read, i)
    return text, i


def _push_back(pushed: list[tuple[int, int]], read: _Input, rest: int | None) -> int:
    """Where reading goes on now: bash reads the rests of the `EOF)` lines it pushed back (each the offset
    past its word, and its line's newline) last first, then `rest`, the rest of the line a substitution
    closed on, if any, then its input."""
    order = pushed[::-1]
    for (_, newline), (start, _) in zip(order, order[1:]):
        read.links[newline] = start
    if rest is not None:
        read.links[order[-1][1]] = rest
    return order[0][0]


def _dollars(out: list[str]) -> int:
    """How many unescaped `$` end what has been read."""
    count = 0
    for piece in reversed(out):
        if piece != "$":
            break
        count += 1
    return count


def _quoted(command: str, i: int, kind: str, extra: list[str], read: _Input) -> tuple[str, int]:
    """The text of a quoted string from `i`, up to its closing quote, as the shell reads it (other ANSI-C
    escapes than \\', \\" and \\\\ stay as written), past text bash has read as here-documents."""
    text: list[str] = []
    if kind == "'":
        while True:
            end = command.find("'", i)
            end = len(command) if end < 0 else end
            newline = command.find("\n", i, end)
            while newline >= 0 and read.after(newline) == newline + 1:
                newline = command.find("\n", newline + 1, end)
            if newline < 0:
                text.append(command[i:end])
                return "".join(text), end + 1
            text.append(command[i:newline + 1])
            i = read.after(newline)
    while i < len(command):
        char = command[i]
        if char == kind[-1]:
            return "".join(text), i + 1
        if char == "\\":
            escaped = command[i + 1:i + 2]
            if kind == '"':
                text.append("" if escaped == "\n" else escaped if escaped in '"\\$`' else command[i:i + 2])
            else:
                text.append(escaped if escaped in "'\"\\" else command[i:i + 2])
            i = read.after(i + 1) if escaped == "\n" else i + 2
        elif kind == '"' and char == "`":
            body, end = _backquoted(command, i + 1, read)
            extra.append(_script(body))
            text.append(command[i:end])
            i = end
        elif kind == '"' and command.startswith("$(", i):
            body, i = _substitution(command, i + 2, extra, read, command.startswith("$((", i))
            extra.append(body)
            text.append("$()")
        else:
            text.append(char)
            i = read.after(i) if char == "\n" else i + 1
    return "".join(text), i


def _backquoted(command: str, i: int, read: _Input) -> tuple[str, int]:
    """The command inside backquotes from `i`, up to the closing backquote, past text bash has read as
    here-documents."""
    text: list[str] = []
    while i < len(command):
        char = command[i]
        if char == "`":
            return "".join(text), i + 1
        if char == "\\" and command[i + 1:i + 2] in ("`", "\\", "$"):
            text.append(command[i + 1])
            i += 2
        else:
            text.append(char)
            i = read.after(i) if char == "\n" else i + 1
    return "".join(text), i


@functools.lru_cache(maxsize=None)  # one command per process, and each backquoted text read apart
def _line_index(command: str) -> dict[tuple[str, bool], dict[str, list[int]]]:
    """Each line's text (as written, and after its leading tabs) to the offsets just past such lines;
    and, for a line holding a `)`, its text before the first `)` less the blanks before that `)` (as
    written, and after its leading tabs) to the offsets where that text starts."""
    index: dict[tuple[str, bool], dict[str, list[int]]] = {
        (kind, tabs): {} for kind in ("line", "paren") for tabs in (False, True)
    }
    start = 0
    for line in command.split("\n"):
        untabbed = line.lstrip("\t")
        index["line", False].setdefault(line, []).append(start + len(line) + 1)
        index["line", True].setdefault(untabbed, []).append(start + len(line) + 1)
        if ")" in line:
            index["paren", False].setdefault(line.split(")", 1)[0].rstrip(" \t"), []).append(start)
            index["paren", True].setdefault(untabbed.split(")", 1)[0].rstrip(" \t"), []).append(
                start + len(line) - len(untabbed))
        start += len(line) + 1
    return index


@functools.lru_cache(maxsize=None)
def _paren_ends(command: str, word: str, tabs: bool) -> list[int]:
    """The offsets just past `word` on each line that starts with it (after its leading tabs, for <<-),
    blanks and a `)`. The index keys such a line by its text before its first `)`, so the word is cut the
    same way, and each line found is checked against the whole word (one that holds a `)` or ends in a
    blank keys lines that are not its end)."""
    starts = _line_index(command)["paren", tabs].get(word.split(")", 1)[0].rstrip(" \t"), [])
    return [start + len(word) for start in starts
            if command.startswith(word, start) and PAREN_END.match(command, start + len(word))]


def _gather(command: str, i: int, ends: list[tuple[str, bool, bool]]) -> tuple[int, list[tuple[int, int]]]:
    """The text of these here-documents, read from `i` as bash reads it, each from where the last ended:
    up to the line that is its word (after its leading tabs, for <<-), or, for one opened inside `$(...)`,
    `<(...)` or `>(...)`, up to a line that starts with the word, blanks and a `)`, whichever comes first,
    as bash reads `EOF)` (its end at a line where other text follows the word before the `)` is not read).
    Returns where the text ends, or, when a word's end never comes, where its text starts (the rest is
    read as commands, more than bash runs: it reads it all as the text, or, inside a substitution, may end
    it at an `EOFX)` line), and each `EOF)` end: the offset past its word and its line's newline."""
    index = _line_index(command)
    pushed: list[tuple[int, int]] = []
    for word, tabs, comsub in ends:
        lines = index["line", tabs].get(word, [])
        k = bisect.bisect_right(lines, i)
        end = lines[k] if k < len(lines) else None
        if comsub:
            pasts = _paren_ends(command, word, tabs)
            j = bisect.bisect_left(pasts, i + len(word))
            if j < len(pasts) and (end is None or pasts[j] - len(word) < end):
                newline = command.find("\n", pasts[j])
                pushed.append((pasts[j], newline))
                i = newline + 1
                continue
        if end is None:
            break
        i = end
    return i, pushed


def _command_tokens(script: str) -> list[str]:
    """Shell words and operators, each newline outside quotes a `;` unless its line goes on."""
    import shlex

    try:
        lexer = shlex.shlex(script, posix=True, punctuation_chars="();<>|&\n")
        lexer.whitespace, lexer.whitespace_split, lexer.commenters = " \t\r", True, ""
        lexed = list(lexer)
    except ValueError:  # a trailing lone backslash, or unbalanced quotes after the RecursionError fallback
        return script.replace("\n", " ; ").split()
    tokens: list[str] = []
    for token in lexed:
        if token.strip("();<>|&\n"):  # a word
            tokens.append(token)
            continue
        while token:  # a run of operator characters, split the way the shell reads it
            operator = next(op for op in SHELL_OPERATORS if token.startswith(op))
            token = token[len(operator):]
            if operator != "\n":
                tokens.append(operator)
            elif tokens and tokens[-1] not in CONTINUED:
                tokens.append(";")
    return tokens


def _commands(tokens: list[str]) -> list[tuple[str | None, list[str]]]:
    """The commands of a shell line, each with the operator before it. The word after a `<<<`
    here-string is the text it feeds, no word of its command."""
    commands, operator, words, fed = [], None, [], False
    for token in tokens:
        if fed:
            fed = False
        elif token in OPERATORS:
            commands.append((operator, words))
            operator, words = token, []
        elif token == "<<<":
            fed = True
        else:
            words.append(token)
    commands.append((operator, words))
    return commands


def _gh_api(words: list[str]) -> bool:
    """Whether this command runs `gh api`: gh as a word or a path to it, then `api` (gh takes no -R before it)."""
    return any((word == "gh" or word.endswith("/gh")) and words[index + 1:index + 2] == ["api"]
               for index, word in enumerate(words))


def _files_named(words: list[str], gh: bool) -> tuple[list[str], bool]:
    """The files a GitHub-writing command sends as a body, and whether it reads one from stdin."""
    options, attached = (GH_FILE_OPTIONS, "-F") if gh else (OTHER_FILE_OPTIONS, "-T")
    if gh and _gh_api(words):  # gh api's -F is a field, which reads a file only as key=@file (read below)
        options, attached = ("--input",), None
    names, redirects, stdin = [], [], not gh and any(word.rsplit("/", 1)[-1] in HTTPIE for word in words)
    for index, word in enumerate(words):
        values = []
        if word in options and index + 1 < len(words):
            values.append(words[index + 1])
        values += [word[len(option) + 1:] for option in options if word.startswith(option + "=")]
        if attached and word.startswith(attached) and len(word) > 2 and word[2] != "=":
            values.append(word[2:])  # an attached -Fbody.md or -Tpayload.json; -Fkey=@file is read below
        at_file = AT_FILE.match(word)
        if at_file:
            values.append(at_file.group(1))
        for value in values:
            if value in STDIN:
                stdin = True
            else:
                names.append(value)
        if word == "<" and index + 1 < len(words):
            redirects.append(words[index + 1])
    return names + (redirects if stdin else []), stdin


def _files_sent(script: str, cwd: object):
    """The text of each regular file, up to 1 MiB, that a GitHub write in this script sends as a body."""
    for name in _names_sent(script):
        text = _read_sent(name, cwd)
        if text is not None:
            yield text


def _read_sent(name: str, cwd: object) -> str | None:
    """The text of the file `name` names, from the event's working directory as it stands before the command
    runs, or None when it is no regular file up to 1 MiB, lies under /proc, /sys or /dev, or cannot be read."""
    from pathlib import Path

    base = Path(cwd) if isinstance(cwd, str) and cwd else Path.cwd()
    try:
        path = (base / Path(name).expanduser()).resolve()
        if str(path).startswith(("/proc/", "/sys/", "/dev/")):  # a kernel file can block a read
            return None
        if path.is_file() and path.stat().st_size <= MAX_FILE_BYTES:
            return path.read_text(encoding="utf-8", errors="replace")
    except (OSError, RuntimeError, ValueError):  # a ~user that does not exist; a NUL in the name
        pass
    return None


def _names_sent(script: str) -> list[str]:
    """The files a GitHub write in this script sends as a body, each once, as the script names them."""
    commands = _commands(_command_tokens(script))
    names = []
    for index, (operator, words) in enumerate(commands):
        line, offset, gh = " ".join(words), 0, False
        for word in words:  # gh as a word of its own or a path to it, wherever it stands (`sudo gh ...`)
            if (word == "gh" or word.endswith("/gh")) and GH_WRITE.match(line, offset + len(word) - 2):
                gh = True
                break
            offset += len(word) + 1
        if not gh and GITHUB_API not in line.lower():
            continue
        files, stdin = _files_named(words, gh)
        names += files
        if stdin and operator in ("|", "|&") and commands[index - 1][1][:1] == ["cat"]:
            names += [word for word in commands[index - 1][1][1:] if not word.startswith("-")]
    return list(dict.fromkeys(names))


def _is_review_request_command(command: str) -> bool:
    """`gh pr comment` or `gh issue comment` with at most one number, -R/--repo anywhere, and the
    review command as its one --body, and nothing else in the command."""
    if command.split(None, 1)[:1] != ["gh"] or "comment" not in command:
        return False
    rest, bodies, words = _tokens(command)[1:], [], []
    while rest:
        token = rest.pop(0)
        if token in ("--body", "-b", "--repo", "-R"):
            if not rest:
                return False
            value = rest.pop(0)
            if token in ("--body", "-b"):
                bodies.append(value)
        elif token.startswith("--body="):
            bodies.append(token[len("--body="):])
        elif token.startswith(("--repo=", "-R")):
            continue
        elif token.startswith("-"):
            return False
        else:
            words.append(token)  # the noun, the verb, the number; a shell operator too, so a second command refuses
    return (
        words[:2] in (["pr", "comment"], ["issue", "comment"])
        and len(words) <= 3
        and len(bodies) == 1
        and REVIEW_REQUEST.fullmatch(bodies[0]) is not None
    )


def _reason(where: str, route: str) -> str:
    return (
        f"Refused by .claude/hooks/codex_mention_guard.py: {where} carries Codex's at-mention (the at sign "
        "followed by codex), which starts a Codex cloud task even mid-sentence or inside backticks. Name "
        "Codex in words (\"Codex\", \"Codex's review command\", \"a review request\") and send it again. The "
        f"only GitHub text that may carry the mention is {route} (lessons/ops-name-codex-without-its-at-mention.md)."
    )


def _bash_refusal(command: str, cwd: object) -> str | None:
    plain = command.replace("\\\n", "").translate(UNQUOTE)  # no quotes, backslashes or continuations
    writes = GH_WRITE.search(command) is not None or GITHUB_API in plain.lower()
    if not writes and "gh" not in plain:
        return None
    script = _script(command)
    words = " ".join(_tokens(script))  # the shell's words, quotes removed: `gh 'pr' comment`, `'ping @'codex`
    if not writes and GH_WRITE.search(words) is None:
        return None
    if MENTION.search(command) or MENTION.search(words):
        return None if _is_review_request_command(command) else _reason("this command", BASH_ROUTE)
    if any(MENTION.search(body) for body in _files_sent(script, cwd)):
        return _reason("a file this command sends", BASH_ROUTE)
    return None


def refusal(event: object) -> str | None:
    """Why this tool call must not run, or None to let it through."""
    if not isinstance(event, dict):
        return None
    tool, tool_input = event.get("tool_name"), event.get("tool_input")
    if not isinstance(tool, str) or not isinstance(tool_input, dict):
        return None
    if tool == "Bash":
        command = tool_input.get("command")
        return _bash_refusal(command, event.get("cwd")) if isinstance(command, str) else None
    parts = tool.split("__")
    if len(parts) >= 3 and parts[0] == "mcp" and "github" in parts[1].lower():
        for field, text in _texts(tool_input):
            if not MENTION.search(text):
                continue
            if tool.endswith(COMMENT_TOOL) and field == "body" and REVIEW_REQUEST.fullmatch(text):
                continue
            return _reason(f"this GitHub write's {field}", MCP_ROUTE)
    return None


def main() -> int:
    reason = refusal(json.load(sys.stdin.buffer))
    if reason is not None:
        decision = {"hookEventName": "PreToolUse", "permissionDecision": "deny", "permissionDecisionReason": reason}
        json.dump({"hookSpecificOutput": decision}, sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
