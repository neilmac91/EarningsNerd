"""PreToolUse hook: refuse an agent's GitHub write whose text carries Codex's at-mention (E63).

The gate for lessons/ops-name-codex-without-its-at-mention.md. The Codex GitHub app starts a cloud
task when its at-mention appears in a pull request's title, body or comment, mid-sentence and inside
backticks too, so GitHub text names Codex in words. The one exception is a new comment that is the
review command alone, with at most the attribution footer: the form the rerun-on-review-request job
of .github/workflows/review-gate.yml matches.

.claude/settings.json runs this before every GitHub MCP tool call and every Bash command. It checks
- a GitHub MCP tool's `title` and `body` arguments, at any depth;
- the whole text of a Bash command that runs `gh pr` or `gh issue` (create, comment, edit, review),
  `gh api`, or curl against api.github.com.
A refusal is a JSON deny on stdout, which Claude Code hands to Claude as the reason; anything else
exits 0 with no output. A crash exits 1, which Claude Code reports as a hook error and does not
block on. The registered command maps Python's own exit 2 (a script it cannot open) to 1, so a
broken install never blocks every GitHub call and every Bash command.

Not checked: text a command reads from a file (`--body-file`, `gh api --input`) or builds from
variables, and sessions that do not load this repository's hooks. Tests:
backend/tests/unit/test_codex_mention_guard.py.
"""
from __future__ import annotations

import json
import re
import shlex
import sys
from collections.abc import Iterator

# Codex's at-mention in any case, ending at a word boundary: "@codexes" names someone else.
MENTION = re.compile(r"@codex\b", re.IGNORECASE)
# The attribution footer agents end every GitHub post with; the server's copy can carry a session path.
FOOTER = r"\s*---\s*_Generated by \[Claude Code\]\(https://claude\.ai/code(?:/[\w-]+)?\)_"
REVIEW_REQUEST = re.compile(rf"@codex review(?:{FOOTER})?\s*", re.IGNORECASE)
COMMENT_TOOL = "mcp__github__add_issue_comment"
TEXT_FIELDS = ("title", "body")
GH_WRITE = re.compile(r"\bgh\s+(?:(?:pr|issue)\s+(?:create|comment|edit|review)|api)\b")
CURL = re.compile(r"\bcurl\b")


def _texts(value: object, field: str | None = None) -> Iterator[tuple[str, str]]:
    """Every `title` and `body` string in a tool call's arguments, at any depth."""
    if isinstance(value, dict):
        for key, item in value.items():
            yield from _texts(item, key)
    elif isinstance(value, list):
        for item in value:
            yield from _texts(item, field)
    elif isinstance(value, str) and field in TEXT_FIELDS:
        yield field, value


def _writes_to_github(command: str) -> bool:
    return GH_WRITE.search(command) is not None or ("api.github.com" in command and CURL.search(command) is not None)


def _is_review_request_command(command: str) -> bool:
    """`gh pr comment <pull request> --body '<the review command>'`, with an optional -R/--repo, alone."""
    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
        lexer.whitespace_split = True
        tokens = list(lexer)
    except ValueError:
        return False
    if tokens[:3] != ["gh", "pr", "comment"]:
        return False
    rest, bodies, positional = tokens[3:], [], []
    while rest:
        token = rest.pop(0)
        if token in ("--body", "-b", "--repo", "-R"):
            if not rest:
                return False
            value = rest.pop(0)
            if token in ("--body", "-b"):
                bodies.append(value)
        elif token.startswith("--body="):
            bodies.append(token.removeprefix("--body="))
        elif token.startswith("--repo="):
            continue
        elif token.startswith("-"):
            return False
        else:
            positional.append(token)  # also a shell operator (`&&`, `;`, `|`), so a second command refuses
    return len(positional) == 1 and len(bodies) == 1 and REVIEW_REQUEST.fullmatch(bodies[0]) is not None


def _reason(where: str) -> str:
    return (
        f"Refused by .claude/hooks/codex_mention_guard.py: {where} carries Codex's at-mention (the at sign "
        "followed by codex), which starts a Codex cloud task even mid-sentence or inside backticks. Name "
        "Codex in words (\"Codex\", \"Codex's review command\", \"a review request\") and send it again. The "
        "only GitHub text that may carry the mention is a new comment that is the review command alone, with "
        "at most the attribution footer (lessons/ops-name-codex-without-its-at-mention.md)."
    )


def refusal(event: object) -> str | None:
    """Why this tool call must not run, or None to let it through."""
    if not isinstance(event, dict):
        return None
    tool, tool_input = event.get("tool_name"), event.get("tool_input")
    if not isinstance(tool, str) or not isinstance(tool_input, dict):
        return None
    if tool == "Bash":
        command = tool_input.get("command")
        if not isinstance(command, str) or not MENTION.search(command) or not _writes_to_github(command):
            return None
        return None if _is_review_request_command(command) else _reason("this command")
    if tool.startswith("mcp__github__"):
        for field, text in _texts(tool_input):
            if not MENTION.search(text):
                continue
            if tool == COMMENT_TOOL and field == "body" and REVIEW_REQUEST.fullmatch(text):
                continue
            return _reason(f"this GitHub write's {field}")
    return None


def main() -> int:
    reason = refusal(json.load(sys.stdin))
    if reason is not None:
        decision = {"hookEventName": "PreToolUse", "permissionDecision": "deny", "permissionDecisionReason": reason}
        json.dump({"hookSpecificOutput": decision}, sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
