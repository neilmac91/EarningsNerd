"""PreToolUse hook: refuse an agent's GitHub write whose text carries Codex's at-mention (E63).

The gate for lessons/ops-name-codex-without-its-at-mention.md. The Codex GitHub app starts a cloud
task when its at-mention appears in a pull request's title, body or comment, mid-sentence and inside
backticks too, so GitHub text names Codex in words. The one exception is a new conversation comment
that is the review command alone, with at most the attribution footer: a form the
rerun-on-review-request job of .github/workflows/review-gate.yml matches.

.claude/settings.json runs this before every Bash command and every call to an MCP server whose name
contains "github" in any case. It checks
- such a tool's `title` and `body` arguments, at any depth;
- a Bash command line whose text, as written or with its quotes removed, names `gh pr` or `gh issue`
  (create or new, comment, edit, review, close, reopen; -R/--repo anywhere before the verb),
  `gh api` or api.github.com: that text, and the files the line's GitHub writes send as a body. The
  line is read as the shell reads it: newlines and `;`, `&`, `&&`, `||`, `|` and `|&` separate
  commands, a backslash-newline joins two lines, a here-document's text is no command once its end
  comes (the line that is its word, or `WORD)` inside `$(...)`), a comment's words are read with
  their quotes inert (so a commented-out write counts), and the text of each command substitution,
  `$(...)` or backquoted, quoted or not, is read as commands of its own, unless it sits in a
  here-document's text. A GitHub write is a command in which a word `gh`, or a path ending in `/gh`,
  starts a `gh pr`/`gh issue` write or `gh api` wherever it stands (`sudo gh api`), or that names
  api.github.com. Its files: gh's `--body-file`, `-F` (attached too) and `--input`; an `@file` value
  (gh api's -F key=@file, curl's -d @file, httpie's key=@file); wget's `--post-file` and
  `--body-file`; curl's `-T` and `--upload-file`; and a file redirected with `<`, or piped from a
  plain `cat`, into a command that reads its body from standard input: one given `-`, /dev/stdin or
  /dev/fd/0, and httpie (`http`, `https`, `xh` or `xhs`, wherever it stands), which reads it
  unasked. Files are read from the event's working directory as they stand before the command runs,
  each once; one larger than 1 MiB, not a regular file, or under /proc, /sys or /dev is not.
A refusal is a JSON deny on stdout, which Claude Code hands to Claude as the reason; anything else
exits 0 with no output. A crash exits 1, which Claude Code reports as a hook error and lets the call
through. The registered command (`python3 -I -S`: standard library only, no PYTHON* variables or
site-packages) maps Python's own exit 2 (a script it cannot open) to 1, so a broken install never
blocks every Bash command and every GitHub call.

Not checked: text a command builds as it runs (a variable, the output of a command or process
substitution, a body piped from anything but a plain cat, a file named relative to a directory the
command changes into first), a command substitution inside a here-document's text, a program other
than httpie that reads its body from standard input unasked, the body files of a command another
shell runs (`bash -c '...'`, a here-document fed to a shell), the commit messages
`gh pr create --fill` copies, a GitHub MCP server registered under a name without "github", a
session that loads no repository hooks, and a person's own write.
Tests: backend/tests/unit/test_codex_mention_guard.py.
"""
from __future__ import annotations

import bisect
import functools
import json
import re
import sys

# Codex's at-mention in any case, ending at a word boundary: "@codexes" names someone else.
MENTION = re.compile(r"@codex\b", re.IGNORECASE)
# The attribution footer agents end every GitHub post with.
FOOTER = r"\s*---\s*_Generated by \[Claude Code\]\(https://claude\.ai/code\)_"
REVIEW_REQUEST = re.compile(rf"@codex review(?:{FOOTER})?\s*", re.IGNORECASE)
TEXT_FIELDS = ("title", "body")
COMMENT_TOOL = "__add_issue_comment"  # the GitHub MCP server's new conversation comment
_REPO = r"(?:\s+(?:-R\s*\S+|--repo(?:=|\s+)\S+))*"  # gh takes -R/--repo before the noun and before the verb
GH_WRITE = re.compile(rf"\bgh{_REPO}\s+(?:(?:pr|issue){_REPO}\s+(?:create|new|comment|edit|review|close|reopen)\b|api\b)")
GITHUB_API = "api.github.com"
OPERATORS = {"|", "|&", "||", "&&", ";", "&"}
# The operators a run of the shell's punctuation characters can hold, longest first.
SHELL_OPERATORS = ("<<<", "<<", "&&", "||", "|&", ">>", ">&", "<&", "&>", ">|", "\n", "(", ")", ";", "&", "|", "<", ">")
CONTINUED = ("|", "|&", "&&", "||")  # a line that ends with one of these goes on to the next
# Options whose value is the file a command sends as a body: gh pr's and gh issue's --body-file and
# -F, gh api's --input; wget's --post-file and --body-file, curl's -T and --upload-file.
GH_FILE_OPTIONS = ("--body-file", "-F", "--input")
OTHER_FILE_OPTIONS = ("--post-file", "--body-file", "-T", "--upload-file")
# An "@file" value: gh api's -F key=@file and --field=key=@file, curl's -d @file or -d@file,
# httpie's key=@file and key:=@file.
AT_FILE = re.compile(r"^(?:(?:[\w.\[\]:-]+=)+|-d)?@(.+)$")
STDIN = ("-", "/dev/stdin", "/dev/fd/0")
HTTPIE = ("http", "https", "xh", "xhs")  # httpie and xh read a body from standard input unasked
MAX_FILE_BYTES = 1 << 20
MCP_ROUTE = (
    "a new conversation comment that is the review command alone, with at most the attribution footer, "
    "sent with the GitHub MCP add_issue_comment tool"
)
BASH_ROUTE = (
    "the review command alone, with at most the attribution footer, sent with the GitHub MCP "
    "add_issue_comment tool or as the whole command `gh pr comment <number> --body '<the command>'` "
    "(an optional -R/--repo; no cd, chaining, redirect or line continuation). A read or an edit that "
    "searches such text with a regular expression (grep, sed, jq test()) can write the pattern as "
    "[@]codex, which matches the mention without carrying it"
)


def _texts(value: object, field: str | None = None):
    """Every `title` and `body` string in a tool call's arguments, at any depth."""
    if isinstance(value, dict):
        for key, item in value.items():
            yield from _texts(item, key)
    elif isinstance(value, list):
        for item in value:
            yield from _texts(item, field)
    elif isinstance(value, str) and field in TEXT_FIELDS:
        yield field, value


def _tokens(command: str) -> list[str]:
    import shlex

    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
        lexer.whitespace_split = True
        lexer.commenters = ""  # sh keeps a mid-word "#"; a stray one only adds words, which refuse
        return list(lexer)
    except ValueError:  # unbalanced quotes: the plain words still name the files
        return command.split()


# The word after `<<` or `<<-` that starts a here-document: quoted, or bare after an optional
# backslash. A shift (`$((1 << 20))`) opens one inside a context that closes before its line ends,
# which drops it.
HEREDOC_WORD = re.compile(r"(-?)[ \t]*(?:'([^'\n]*)'|\"([^\"\n]*)\"|\\?([\w.-]+))")
WORD_START = " \t\n;&|()<>"  # a `#` first or after one of these starts a comment
UNQUOTE = str.maketrans("", "", "'\"\\")


def _literal(text: str) -> str:
    """`text` as one single-quoted shell word."""
    return "'" + text.replace("'", "'\\''") + "'"


def _script(command: str) -> str:
    """The command rewritten for a plain word splitter, as the shell reads it: each quoted string one
    single-quoted word, backslash-newline continuations joined, the quotes, backquotes and backslashes
    in a comment escaped (its words stay), each here-document's `<<WORD` dropped and its text too once
    its end comes, and the text of each command substitution, `$(...)` or backquoted, quoted or not,
    added as lines of its own (in the line, a `$(...)` reads as `$()`)."""
    extra: list[str] = []
    try:
        text = _scan(command, 0, "", extra)[0]
    except RecursionError:  # substitutions nested past Python's limit: read the line as written
        return command
    return "\n".join([text, *extra])


def _scan(command: str, i: int, closer: str, extra: list[str]) -> tuple[str, int]:
    """The commands from `i` up to `closer` (`)` for a subshell or a substitution, "" for the end)."""
    out: list[str] = []
    ends: list[tuple[str, bool]] = []
    while i < len(command):
        char = command[i]
        if closer and char == closer:
            return "".join(out), i + 1
        if char == "\\":
            if command[i + 1:i + 2] != "\n":  # an escape stays; a backslash-newline joins the lines
                out.append(command[i:i + 2])
            i += 2
        elif char in "'\"":
            kind = char
            if _dollars(out) % 2:  # $'...', which reads escapes, or $"..."
                out.pop()
                kind = "$'" if char == "'" else char
            text, i = _quoted(command, i + 1, kind, extra)
            out.append(_literal(text))
        elif char == "`":
            text, i = _backquoted(command, i + 1)
            extra.append(_script(text))
            out.append(_literal(text))
        elif command.startswith("$(", i):
            text, i = _scan(command, i + 2, ")", extra)
            extra.append(text)
            out.append("'$()'")  # its text is read on lines of its own
        elif char == "(":
            text, i = _scan(command, i + 1, ")", extra)
            out.append("(" + text + ")")
        elif char == "#" and (not out or (out[-1][-1] in WORD_START and out[-1][0] != "\\")):  # `a\ #` is one word
            end = command.find("\n", i)
            end = len(command) if end < 0 else end
            out.append(re.sub(r"(['\"\\\\`])", r"\\\1", command[i:end]))  # its quotes start nothing
            i = end
        elif command.startswith("<<<", i):
            out.append("<<<")
            i += 3
        elif command.startswith("<<", i) and (heredoc := HEREDOC_WORD.match(command, i + 2)):
            ends.append((next(word for word in heredoc.groups()[1:] if word is not None), heredoc.group(1) == "-"))
            out.append(" ")
            i = heredoc.end()
        elif char == "\n" and ends:
            body_end = _heredoc_end(command, i + 1, ends, closer)
            out.append("\n")
            i, ends = (i + 1 if body_end is None else body_end), []  # no end: read on, so this over-reads
        else:
            out.append(char)
            i += 1
    return "".join(out), i


def _dollars(out: list[str]) -> int:
    """How many unescaped `$` end what has been read."""
    count = 0
    for piece in reversed(out):
        if piece != "$":
            break
        count += 1
    return count


def _quoted(command: str, i: int, kind: str, extra: list[str]) -> tuple[str, int]:
    """The text of a quoted string from `i`, up to its closing quote, as the shell reads it (other
    ANSI-C escapes than \\', \\" and \\\\ stay as written)."""
    if kind == "'":
        end = command.find("'", i)
        end = len(command) if end < 0 else end
        return command[i:end], end + 1
    text: list[str] = []
    while i < len(command):
        char = command[i]
        if char == kind[-1]:
            return "".join(text), i + 1
        if char == "\\":
            escaped = command[i + 1:i + 2]
            if kind == '"':
                text.append("" if escaped == "\n" else escaped if escaped in '"\\$`' else command[i:i + 2])
            else:
                text.append(escaped if escaped in "'\"\\" else command[i:i + 2])
            i += 2
        elif kind == '"' and char == "`":
            body, end = _backquoted(command, i + 1)
            extra.append(_script(body))
            text.append(command[i:end])
            i = end
        elif kind == '"' and command.startswith("$(", i):
            body, i = _scan(command, i + 2, ")", extra)
            extra.append(body)
            text.append("$()")
        else:
            text.append(char)
            i += 1
    return "".join(text), i


def _backquoted(command: str, i: int) -> tuple[str, int]:
    """The command inside backquotes from `i`, up to the closing backquote."""
    text: list[str] = []
    while i < len(command):
        char = command[i]
        if char == "`":
            return "".join(text), i + 1
        if char == "\\" and command[i + 1:i + 2] in ("`", "\\", "$"):
            text.append(command[i + 1])
            i += 2
        else:
            text.append(char)
            i += 1
    return "".join(text), i


@functools.lru_cache(maxsize=4)
def _line_ends(command: str) -> tuple[dict[str, list[int]], dict[str, list[int]]]:
    """Each line's text, as written and after its leading tabs, to the offsets just past such lines."""
    plain: dict[str, list[int]] = {}
    tabbed: dict[str, list[int]] = {}
    past = 0
    for line in command.split("\n"):
        past += len(line) + 1
        plain.setdefault(line, []).append(past)
        tabbed.setdefault(line.lstrip("\t"), []).append(past)
    return plain, tabbed


def _heredoc_end(command: str, i: int, ends: list[tuple[str, bool]], closer: str) -> int | None:
    """Where the text of these here-documents, from `i`, ends: past the line that is each one's word in
    turn (after its leading tabs, for <<-), or, inside `$(...)`, just past the word at the start of a
    line that goes on to the `)`, which bash reads as the end (`EOF)`); None when a word's end never
    comes."""
    for word, tabs in ends:
        pasts = _line_ends(command)[tabs].get(word, [])
        k = bisect.bisect_right(pasts, i)
        if closer:
            closing = re.compile("^" + ("\t*" if tabs else "") + re.escape(word) + "(?=[ \t]*" + re.escape(closer) + ")", re.M)
            match = closing.search(command, i, pasts[k] if k < len(pasts) else len(command))
            if match:
                return match.end()
        if k == len(pasts):
            return None
        i = pasts[k]
    return i


def _command_tokens(script: str) -> list[str]:
    """Shell words and operators, each newline outside quotes a `;` unless its line goes on."""
    import shlex

    try:
        lexer = shlex.shlex(script, posix=True, punctuation_chars="();<>|&\n")
        lexer.whitespace, lexer.whitespace_split, lexer.commenters = " \t\r", True, ""
        lexed = list(lexer)
    except ValueError:  # a trailing lone backslash, or unbalanced quotes after the RecursionError fallback
        return script.replace("\n", " ; ").split()
    tokens: list[str] = []
    for token in lexed:
        if token.strip("();<>|&\n"):  # a word
            tokens.append(token)
            continue
        while token:  # a run of operator characters, split the way the shell reads it
            operator = next(op for op in SHELL_OPERATORS if token.startswith(op))
            token = token[len(operator):]
            if operator != "\n":
                tokens.append(operator)
            elif tokens and tokens[-1] not in CONTINUED:
                tokens.append(";")
    return tokens


def _commands(tokens: list[str]) -> list[tuple[str | None, list[str]]]:
    """The commands of a shell line, each with the operator before it. The word after a `<<<`
    here-string is the text it feeds, no word of its command."""
    commands, operator, words, fed = [], None, [], False
    for token in tokens:
        if fed:
            fed = False
        elif token in OPERATORS:
            commands.append((operator, words))
            operator, words = token, []
        elif token == "<<<":
            fed = True
        else:
            words.append(token)
    commands.append((operator, words))
    return commands


def _files_named(words: list[str], gh: bool) -> tuple[list[str], bool]:
    """The files a GitHub-writing command sends as a body, and whether it reads one from stdin."""
    options, attached = (GH_FILE_OPTIONS, "-F") if gh else (OTHER_FILE_OPTIONS, "-T")
    names, redirects, stdin = [], [], not gh and any(word.rsplit("/", 1)[-1] in HTTPIE for word in words)
    for index, word in enumerate(words):
        values = []
        if word in options and index + 1 < len(words):
            values.append(words[index + 1])
        values += [word[len(option) + 1:] for option in options if word.startswith(option + "=")]
        if word.startswith(attached) and len(word) > 2 and word[2] != "=":
            values.append(word[2:])  # an attached -Fbody.md or -Tpayload.json; -Fkey=@file is read below
        at_file = AT_FILE.match(word)
        if at_file:
            values.append(at_file.group(1))
        for value in values:
            if value in STDIN:
                stdin = True
            else:
                names.append(value)
        if word == "<" and index + 1 < len(words):
            redirects.append(words[index + 1])
    return names + (redirects if stdin else []), stdin


def _files_sent(script: str, cwd: object):
    """The text of each regular file, up to 1 MiB, that a GitHub write in this script sends as a body."""
    from pathlib import Path

    commands = _commands(_command_tokens(script))
    names = []
    for index, (operator, words) in enumerate(commands):
        line, offset, gh = " ".join(words), 0, False
        for word in words:  # gh as a word of its own or a path to it, wherever it stands (`sudo gh ...`)
            if (word == "gh" or word.endswith("/gh")) and GH_WRITE.match(line, offset + len(word) - 2):
                gh = True
                break
            offset += len(word) + 1
        if not gh and GITHUB_API not in line.lower():
            continue
        files, stdin = _files_named(words, gh)
        names += files
        if stdin and operator in ("|", "|&") and commands[index - 1][1][:1] == ["cat"]:
            names += [word for word in commands[index - 1][1][1:] if not word.startswith("-")]
    base = Path(cwd) if isinstance(cwd, str) and cwd else Path.cwd()
    for name in dict.fromkeys(names):  # each file once
        try:
            path = (base / Path(name).expanduser()).resolve()
            if str(path).startswith(("/proc/", "/sys/", "/dev/")):  # a kernel file can block a read
                continue
            if path.is_file() and path.stat().st_size <= MAX_FILE_BYTES:
                yield path.read_text(encoding="utf-8", errors="replace")
        except (OSError, RuntimeError, ValueError):  # a ~user that does not exist; a NUL in the name
            continue


def _is_review_request_command(command: str) -> bool:
    """`gh pr comment` or `gh issue comment` with at most one number, -R/--repo anywhere, and the
    review command as its one --body, and nothing else in the command."""
    if command.split(None, 1)[:1] != ["gh"] or "comment" not in command:
        return False
    rest, bodies, words = _tokens(command)[1:], [], []
    while rest:
        token = rest.pop(0)
        if token in ("--body", "-b", "--repo", "-R"):
            if not rest:
                return False
            value = rest.pop(0)
            if token in ("--body", "-b"):
                bodies.append(value)
        elif token.startswith("--body="):
            bodies.append(token[len("--body="):])
        elif token.startswith(("--repo=", "-R")):
            continue
        elif token.startswith("-"):
            return False
        else:
            words.append(token)  # the noun, the verb, the number; a shell operator too, so a second command refuses
    return (
        words[:2] in (["pr", "comment"], ["issue", "comment"])
        and len(words) <= 3
        and len(bodies) == 1
        and REVIEW_REQUEST.fullmatch(bodies[0]) is not None
    )


def _reason(where: str, route: str) -> str:
    return (
        f"Refused by .claude/hooks/codex_mention_guard.py: {where} carries Codex's at-mention (the at sign "
        "followed by codex), which starts a Codex cloud task even mid-sentence or inside backticks. Name "
        "Codex in words (\"Codex\", \"Codex's review command\", \"a review request\") and send it again. The "
        f"only GitHub text that may carry the mention is {route} (lessons/ops-name-codex-without-its-at-mention.md)."
    )


def _bash_refusal(command: str, cwd: object) -> str | None:
    plain = command.replace("\\\n", "").translate(UNQUOTE)  # no quotes, backslashes or continuations
    writes = GH_WRITE.search(command) is not None or GITHUB_API in plain.lower()
    if not writes and "gh" not in plain:
        return None
    script = _script(command)
    words = " ".join(_tokens(script))  # the shell's words, quotes removed: `gh 'pr' comment`, `'ping @'codex`
    if not writes and GH_WRITE.search(words) is None:
        return None
    if MENTION.search(command) or MENTION.search(words):
        return None if _is_review_request_command(command) else _reason("this command", BASH_ROUTE)
    if any(MENTION.search(body) for body in _files_sent(script, cwd)):
        return _reason("a file this command sends", BASH_ROUTE)
    return None


def refusal(event: object) -> str | None:
    """Why this tool call must not run, or None to let it through."""
    if not isinstance(event, dict):
        return None
    tool, tool_input = event.get("tool_name"), event.get("tool_input")
    if not isinstance(tool, str) or not isinstance(tool_input, dict):
        return None
    if tool == "Bash":
        command = tool_input.get("command")
        return _bash_refusal(command, event.get("cwd")) if isinstance(command, str) else None
    parts = tool.split("__")
    if len(parts) >= 3 and parts[0] == "mcp" and "github" in parts[1].lower():
        for field, text in _texts(tool_input):
            if not MENTION.search(text):
                continue
            if tool.endswith(COMMENT_TOOL) and field == "body" and REVIEW_REQUEST.fullmatch(text):
                continue
            return _reason(f"this GitHub write's {field}", MCP_ROUTE)
    return None


def main() -> int:
    reason = refusal(json.load(sys.stdin.buffer))
    if reason is not None:
        decision = {"hookEventName": "PreToolUse", "permissionDecision": "deny", "permissionDecisionReason": reason}
        json.dump({"hookSpecificOutput": decision}, sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
