def _registered() -> list[dict]:
    """The PreToolUse entries of .claude/settings.json that run the guard."""
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    return [
        entry for entry in settings["hooks"]["PreToolUse"]
        if any("codex_mention_guard.py" in hook.get("command", "") for hook in entry["hooks"])
    ]


def _run(stdin: str, project_dir: Path = ROOT, extra_env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Run the command .claude/settings.json registers, as Claude Code does (`/bin/sh -c`), within its timeout."""
    [hook] = [hook for entry in _registered() for hook in entry["hooks"]]
    env = {**os.environ, **(extra_env or {}), "CLAUDE_PROJECT_DIR": str(project_dir)}
    return subprocess.run(["sh", "-c", hook["command"]], input=stdin, capture_output=True, text=True, env=env,
                          timeout=hook["timeout"])


def _event(tool: str, tool_input: object, cwd: Path = ROOT) -> str:
    return json.dumps({
        "session_id": "s", "transcript_path": "/dev/null", "cwd": str(cwd), "permission_mode": "default",
        "hook_event_name": "PreToolUse", "tool_name": tool, "tool_input": tool_input, "tool_use_id": "toolu_1",
    })


def _decision(tool: str, tool_input: object, cwd: Path = ROOT, extra_env: dict[str, str] | None = None) -> dict | None:
    proc = _run(_event(tool, tool_input, cwd), extra_env=extra_env)
    assert proc.returncode == 0, proc.stderr
    if not proc.stdout:
        return None
    parsed = json.loads(proc.stdout)
    # Nothing beside the decision: a top-level "continue": false, for one, would stop Claude's turn.
    assert list(parsed) == ["hookSpecificOutput"]
    output = parsed["hookSpecificOutput"]
    assert sorted(output) == ["hookEventName", "permissionDecision", "permissionDecisionReason"]
    assert output["hookEventName"] == "PreToolUse"
    return output


def _refused(decision: dict | None, where: str, route: str) -> None:
    assert decision is not None, "the hook let it through"
    assert decision["permissionDecision"] == "deny"
    reason = decision["permissionDecisionReason"]
    assert f"{where} carries Codex's at-mention" in reason
    assert "lessons/ops-name-codex-without-its-at-mention.md" in reason
    # The reason names the route that would have been accepted.
    assert route in reason
    # An agent that quotes the reason into its next write must not start a task with it.
    assert re.search(r"@codex\b", reason, re.IGNORECASE) is None


