"""Gate for `.claude/hooks/codex_mention_guard.py`, the PreToolUse hook that refuses an agent's GitHub
write carrying Codex's at-mention (E63; lessons/ops-name-codex-without-its-at-mention.md).

Each case runs the hook the way `.claude/settings.json` registers it: the registered command, through
the shell, with CLAUDE_PROJECT_DIR set, on the event Claude Code sends. A refusal is a JSON deny on
stdout with exit 0; a call let through exits 0 with no output. The registration is pinned too: the
matcher reaches Bash and every GitHub MCP server, and a hook the shell cannot run exits 1 (a hook error
Claude Code does not block on), never Python's own exit 2, which Claude Code would read as a refusal
of every Bash command and every GitHub call. The gaps the lesson names are planted as cases that pass
through, so closing one is a deliberate change here.
"""
