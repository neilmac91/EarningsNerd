@pytest.mark.parametrize(("tool", "tool_input", "field"), REFUSED.values(), ids=REFUSED.keys())
def test_a_github_write_carrying_the_mention_is_refused(tool: str, tool_input: dict, field: str) -> None:
    decision = _decision(tool, tool_input)
    assert decision is not None, "the hook let it through"
    assert decision["permissionDecision"] == "deny"
    reason = decision["permissionDecisionReason"]
    assert f"this GitHub write's {field} carries Codex's at-mention" in reason
    assert "lessons/ops-name-codex-without-its-at-mention.md" in reason
    # An agent that quotes the reason into its next write must not start a task with it.
    assert re.search(r"@codex\b", reason, re.IGNORECASE) is None


@pytest.mark.parametrize("command", REFUSED_COMMANDS.values(), ids=REFUSED_COMMANDS.keys())
def test_a_bash_github_write_carrying_the_mention_is_refused(command: str) -> None:
    decision = _decision("Bash", {"command": command, "description": "x"})
    assert decision is not None, "the hook let it through"
    assert decision["permissionDecision"] == "deny"
    assert "this command carries Codex's at-mention" in decision["permissionDecisionReason"]


@pytest.mark.parametrize(("tool", "tool_input"), ALLOWED.values(), ids=ALLOWED.keys())
def test_everything_else_goes_through_untouched(tool: str, tool_input: dict) -> None:
    assert _decision(tool, tool_input) is None


@pytest.mark.parametrize("command", ALLOWED_COMMANDS.values(), ids=ALLOWED_COMMANDS.keys())
def test_other_bash_commands_go_through_untouched(command: str) -> None:
    assert _decision("Bash", {"command": command, "description": "x"}) is None


@pytest.mark.parametrize("event", [
    json.dumps([]),
    json.dumps({"hook_event_name": "PreToolUse", "tool_name": COMMENT}),
    _event(COMMENT, None),
    _event(COMMENT, {"body": None}),
    _event("Bash", {"command": None}),
])
def test_an_event_of_another_shape_goes_through(event: str) -> None:
    proc = _run(event)
    assert (proc.returncode, proc.stdout) == (0, "")


def test_a_hook_that_cannot_run_is_a_hook_error_never_a_refusal(tmp_path: Path) -> None:
    # Python exits 2 when it cannot open its script, and exit 2 from a PreToolUse hook blocks the call;
    # the registered command maps it to 1, a hook error Claude Code reports without blocking.
    assert subprocess.run(["python3", str(tmp_path / "missing.py")], capture_output=True).returncode == 2
    missing = _run(_event(COMMENT, {"body": f"{MENTION} please"}), project_dir=tmp_path)
    assert (missing.returncode, missing.stdout) == (1, "")
    crash = _run("not json")
    assert (crash.returncode, crash.stdout) == (1, "")


def test_the_hook_is_registered_before_bash_and_every_github_tool() -> None:
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    entries = [
        entry for entry in settings["hooks"]["PreToolUse"]
        if any("codex_mention_guard.py" in hook.get("command", "") for hook in entry["hooks"])
    ]
    assert entries == [{"matcher": MATCHER, "hooks": [{"type": "command", "command": COMMAND, "timeout": 10}]}]
    assert HOOK.is_file()
    # Claude Code tests a matcher holding regex characters as an unanchored JavaScript RegExp, which
    # Python's re.search reads the same way for this pattern.
    matcher = re.compile(MATCHER)
    assert [tool for tool in ("Bash", *GITHUB_WRITE_TOOLS) if not matcher.search(tool)] == []
    assert [tool for tool in ("Edit", "Write", "BashOutput", "mcp__Claude_Docs__update") if matcher.search(tool)] == []
