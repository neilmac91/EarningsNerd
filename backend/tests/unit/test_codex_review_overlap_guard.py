"""Gate for `.claude/hooks/codex_review_overlap_guard.py`, the PreToolUse hook that refuses a ready mark or
a Codex review request while a Codex review of the pull request is still running, or asked for and not yet
shown (lessons/ops-merge-after-the-ready-marks-own-codex-review.md).

Each case runs the hook the way `.claude/settings.json` registers it: the registered command, through the
shell, with CLAUDE_PROJECT_DIR set, on the event Claude Code sends. GitHub is a fake on the loopback
(CODEX_OVERLAP_GUARD_API) that serves the pull request's comments, its draft flag and opening, its timeline and
the summary comment's edit history the way GitHub does (a summary never edited has no history), and records
every request. The summaries are written in Codex's own format, pinned below against a body read from #1530.
A refusal is a JSON deny on stdout with exit 0; a call the hook could not check goes through with a note to
Claude (`additionalContext`, no decision); anything else exits 0 with no output. The registration is pinned
too, and a hook the shell cannot run exits 1 (a hook error Claude Code does not block on), never Python's own
exit 2.
"""
