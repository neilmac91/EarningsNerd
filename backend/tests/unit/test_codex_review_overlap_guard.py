def _registered() -> list[dict]:
    """The PreToolUse entries of .claude/settings.json that run the hook."""
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    return [entry for entry in settings["hooks"]["PreToolUse"]
            if any("codex_review_overlap_guard.py" in hook.get("command", "") for hook in entry["hooks"])]


def _env(api: str | None, extra: dict[str, str] | None = None, drop: tuple[str, ...] = ()) -> dict[str, str]:
    # A git hook running pytest sets GIT_DIR and the like, which would point the hook's git at that repository.
    env = {key: value for key, value in os.environ.items()
           if key not in drop and key != "GH_REPO" and not key.startswith("GIT_")}
    env.update({"CLAUDE_PROJECT_DIR": str(ROOT), "GH_TOKEN": TOKEN, "NO_PROXY": "127.0.0.1,localhost",
                "no_proxy": "127.0.0.1,localhost"})
    # Anything bound elsewhere than the loopback fake goes to a closed port, so no case can reach GitHub, even if
    # the hook's reads stopped going through its own transport.
    env.update({name: "http://127.0.0.1:9" for name in ("HTTPS_PROXY", "https_proxy", "HTTP_PROXY", "http_proxy")})
    if api is None:
        env.pop("CODEX_OVERLAP_GUARD_API", None)
    else:
        env["CODEX_OVERLAP_GUARD_API"] = api
    env.update(extra or {})
    return env


def _run(stdin: str, env: dict[str, str]) -> subprocess.CompletedProcess[str]:
    """Run the command .claude/settings.json registers, as Claude Code does (`/bin/sh -c`), within its timeout."""
    [hook] = [hook for entry in _registered() for hook in entry["hooks"]]
    return subprocess.run(["sh", "-c", hook["command"]], input=stdin, capture_output=True, text=True, env=env,
                          timeout=hook["timeout"])


def _event(tool: str, tool_input: object, cwd: Path = ROOT) -> str:
    return json.dumps({
        "session_id": "s", "transcript_path": "/dev/null", "cwd": str(cwd), "permission_mode": "default",
        "hook_event_name": "PreToolUse", "tool_name": tool, "tool_input": tool_input, "tool_use_id": "toolu_1",
    })


def _output(github: FakeGitHub | None, tool: str, tool_input: object, cwd: Path = ROOT,
            env: dict[str, str] | None = None) -> dict | None:
    proc = _run(_event(tool, tool_input, cwd), env or _env(github.url if github else None))
    assert proc.returncode == 0, proc.stderr
    if not proc.stdout:
        return None
    parsed = json.loads(proc.stdout)
    # Nothing beside the hook's output: a top-level "continue": false, for one, would stop Claude's turn.
    assert list(parsed) == ["hookSpecificOutput"]
    output = parsed["hookSpecificOutput"]
    assert output["hookEventName"] == "PreToolUse"
    return output


def _refused(output: dict | None) -> str:
    assert output is not None, "the hook let it through"
    assert sorted(output) == ["hookEventName", "permissionDecision", "permissionDecisionReason"]
    assert output["permissionDecision"] == "deny"
    reason = output["permissionDecisionReason"]
    assert reason.startswith("Refused by .claude/hooks/codex_review_overlap_guard.py: ")
    assert LESSON in reason
    # An agent that quotes the reason into its next write must not start a Codex task with it.
    assert re.search(r"@codex\b", reason, re.IGNORECASE) is None
    return reason


def _overlap(output: dict | None, number: int = 7) -> str:
    """Refused for a review that may still be running on o/r#number, read from its own pull request."""
    reason = _refused(output)
    assert f"on o/r#{number} would start a Codex review while another may still be running: " in reason
    return reason


def _noted(output: dict | None) -> str:
    """Let through unchecked, with a note to Claude and no decision, so the normal permission flow applies."""
    assert output is not None, "the hook said nothing"
    assert sorted(output) == ["additionalContext", "hookEventName"]
    note = output["additionalContext"]
    assert note.startswith(".claude/hooks/codex_review_overlap_guard.py let this call through unchecked: ")
    assert LESSON in note
    assert re.search(r"@codex\b", note, re.IGNORECASE) is None
    return note


def _review_request(number: int = 7) -> tuple[str, dict]:
    return COMMENT, {"owner": "o", "repo": "r", "issue_number": number, "body": REQUEST}


def _ready_mark(**extra: object) -> tuple[str, dict]:
    return UPDATE, {"owner": "o", "repo": "r", "pullNumber": 7, "draft": False, **extra}


