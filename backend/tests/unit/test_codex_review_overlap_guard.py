def summary(status: str, at: datetime, head: str = HEAD, trigger: str = READY, findings: bool = False) -> str:
    """A Codex summary comment's body, in the format GitHub serves it."""
    done = status != "running"
    state = {"code_review": {"commit_sha": head, "has_any_findings": findings if done else None,
                             "has_unresolved_findings": findings if done else None, "status": status},
             "security_review": {"commit_sha": None, "has_any_findings": None, "has_unresolved_findings": None,
                                 "status": None}}
    marker = json.dumps(state, separators=(",", ":")).replace("{", "&#123;").replace("}", "&#125;")
    label = {"running": "🔄 **Running** since", "completed": "✅ **Completed**"}[status]
    stamp_ = at.strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    row = (f"| 📝 **Code Review** | {label} <relative-time datetime=\"{stamp_}\">{stamp_}</relative-time> | "
           f"`{head[:7]}` | {trigger} |")
    return ("<!-- codex-pull-request-review-summary -->\n"
            f"<!-- codex-review-state:v1 {marker} -->\n\n## Codex Review Summary\n\nThis comment shows the latest "
            "Codex review activity on this pull request.\n\n| Review | Status | Commit | Review trigger |\n"
            "| --- | --- | --- | --- |\n" + row + ABOUT)


def ago(minutes: float) -> datetime:
    return datetime.now(timezone.utc) - timedelta(minutes=minutes)


def stamp(at: datetime) -> str:
    return at.strftime("%Y-%m-%dT%H:%M:%SZ")


def started(body: str) -> str:
    """The review time a summary body names, as the hook's reason prints it."""
    value = re.search(r'datetime="([^"]+)"', body)[1]
    return datetime.fromisoformat(value.replace("Z", "+00:00")).strftime("%H:%M:%S")


def version(status: str, minutes: float, head: str = HEAD, trigger: str = READY, editor: dict = EDITOR) -> dict:
    """One version of the summary in its edit history: the body as it read then, edited when it started or ended."""
    at = ago(minutes)
    return {"editedAt": stamp(at + timedelta(seconds=1)), "diff": summary(status, at, head, trigger), "editor": editor}


def codex_comment(body: str, node: str = "IC_summary", created: str = "2026-10-24T09:00:00Z",
                  updated: str | None = None, number: int = 1) -> dict:
    return {"id": number, "node_id": node, "user": CODEX, "body": body, "created_at": created,
            "updated_at": updated or created}


def person_comment(number: int, body: str = "Looks good.", minutes: float | None = None) -> dict:
    created = stamp(ago(minutes)) if minutes is not None else "2026-10-24T08:00:00Z"
    return {"id": 100 + number, "node_id": f"IC_{number}", "user": PERSON, "body": body, "created_at": created,
            "updated_at": created}


class FakeGitHub:
    """GitHub's REST comments, pulls and timeline endpoints and its GraphQL edit history, for pull request PR."""

    def __init__(self) -> None:
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), self._handler())
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        self.reset()

    def reset(self) -> None:
        self.comments: list[dict] = []
        self.histories: dict[str, list[dict]] = {}
        self.timeline: list[dict] = []
        self.draft: object = True
        self.created = LONG_AGO
        self.status = 200
        self.hold: threading.Event | None = None  # GETs wait for it, ten seconds at most, before the fake answers
        self.redirect: str | None = None  # GETs answer 302 to this base URL, the path kept
        self.graphql_status = 200
        self.graphql_errors = False
        self.comment_bodies: list[str] = []  # bodies the summary shows on successive reads, the last repeating
        self.requests: list[tuple[str, str, dict, str]] = []

    def running(self, minutes: float, head: str = HEAD, trigger: str = READY) -> str:
        """The summary shows a review Running since `minutes` ago, as Codex first posts it: never edited, so GitHub
        serves no edit history for it. Returns the body."""
        at = ago(minutes)
        body = summary("running", at, head, trigger)
        receipt = {**codex_comment(RECEIPT, "IC_receipt", stamp(at + timedelta(seconds=30)), number=2)}
        self.comments = [codex_comment(body, created=stamp(at), updated=stamp(at)), receipt]
        self.histories = {"IC_summary": []}
        return body

    def history(self, versions: list[dict]) -> None:
        """The summary's edit history, newest first; the comment reads as its newest version, last edited then."""
        self.comments = [codex_comment(versions[0]["diff"], updated=versions[0]["editedAt"])]
        self.histories = {"IC_summary": versions}

    def paths(self) -> list[str]:
        return [path.split("?")[0] for _, path, _, _ in self.requests]

    def _handler(self) -> type[BaseHTTPRequestHandler]:
        fake = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args: object) -> None:  # quiet
                pass

            def _send(self, payload: object, status: int = 200) -> None:
                data = json.dumps(payload).encode("utf-8")
                self.send_response(status)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def _page(self, items: list[dict]) -> None:
                query = parse_qs(urlsplit(self.path).query)
                page, size = int(query["page"][0]), int(query["per_page"][0])
                self._send(items[(page - 1) * size:page * size])

            def do_GET(self) -> None:  # noqa: N802
                fake.requests.append(("GET", self.path, dict(self.headers), ""))
                if fake.hold is not None and fake.hold.wait(10):
                    return  # let go once the client stopped waiting: nobody is left to answer
                if fake.redirect:
                    self.send_response(302)
                    self.send_header("Location", fake.redirect + self.path)
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
                if fake.status != 200:
                    return self._send({"message": "unavailable"}, fake.status)
                path = urlsplit(self.path).path
                owner, repo, number = PR
                if path == f"/repos/{owner}/{repo}/pulls/{number}":
                    return self._send({"number": number, "draft": fake.draft, "created_at": fake.created})
                if path == f"/repos/{owner}/{repo}/issues/{number}/timeline":
                    return self._page(fake.timeline)
                if path == f"/repos/{owner}/{repo}/issues/{number}/comments":
                    comments = [dict(comment) for comment in fake.comments]
                    if fake.comment_bodies:
                        body = fake.comment_bodies.pop(0) if len(fake.comment_bodies) > 1 else fake.comment_bodies[0]
                        for comment in comments:
                            if comment["user"] == CODEX:
                                comment["body"] = body
                    return self._page(comments)
                return self._send({"message": "Not Found"}, 404)

            def do_POST(self) -> None:  # noqa: N802
                body = self.rfile.read(int(self.headers["Content-Length"])).decode("utf-8")
                fake.requests.append(("POST", self.path, dict(self.headers), body))
                if fake.status != 200:
                    return self._send({"message": "unavailable"}, fake.status)
                if self.path != "/graphql":
                    return self._send({"message": "Not Found"}, 404)
                if fake.graphql_status != 200:
                    return self._send({"message": "GitHub GraphQL is not available"}, fake.graphql_status)
                if fake.graphql_errors:
                    return self._send({"errors": [{"message": "Something went wrong"}]})
                variables = json.loads(body)["variables"]
                edits = fake.histories.get(variables["id"], [])
                start = int(variables["after"] or 0)
                more = start + 100 < len(edits)
                return self._send({"data": {"node": {"userContentEdits": {
                    "nodes": edits[start:start + 100],
                    "pageInfo": {"hasNextPage": more, "endCursor": str(start + 100) if more else None}}}}})

        return Handler


