def _load_hook():
    spec = importlib.util.spec_from_file_location("codex_review_overlap_guard_under_test", HOOK)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


