def _record_timeouts(reader: object, monkeypatch: pytest.MonkeyPatch, then: object) -> list[object]:
    """The timeout each of the reader's requests is given, recorded before `then` takes the request."""
    timeouts: list[object] = []

    def open_recorded(request: object, **kwargs: object) -> object:
        timeouts.append(kwargs.get("timeout"))
        return then(request, **kwargs)

    monkeypatch.setattr(reader.opener, "open", open_recorded)
    return timeouts


def test_a_request_past_its_timeout_is_abandoned(github: FakeGitHub, monkeypatch: pytest.MonkeyPatch) -> None:
    # The fake holds its answer until the test lets it go, so only the request's own timeout can end the wait: the
    # test reads the timeout the request was given, never how long it waited (test_wall_clock_bounds.py).
    module = _load_hook()
    monkeypatch.setenv("CODEX_OVERLAP_GUARD_API", github.url)
    monkeypatch.setenv("NO_PROXY", "127.0.0.1")
    monkeypatch.setattr(module, "REQUEST_TIMEOUT", 0.3)
    reader = module._Reader(TOKEN, time.monotonic() + 30)
    timeouts = _record_timeouts(reader, monkeypatch, reader.opener.open)
    github.hold = threading.Event()
    try:
        with pytest.raises(OSError) as raised:  # urllib's timeout: TimeoutError, or URLError around it
            reader.request("repos/o/r/pulls/7")
    finally:
        github.hold.set()
    assert isinstance(getattr(raised.value, "reason", raised.value), TimeoutError)
    assert timeouts == [0.3]


def test_a_request_ends_with_the_call_budget(monkeypatch: pytest.MonkeyPatch) -> None:
    # Two seconds of the call's budget left: the request may wait those two, not REQUEST_TIMEOUT's ten.
    module = _load_hook()
    monkeypatch.setattr(module, "time", SimpleNamespace(monotonic=lambda: 100.0))
    reader = module._Reader(TOKEN, 102.0)
    timeouts = _record_timeouts(reader, monkeypatch, lambda request, **kwargs: io.BytesIO(b"{}"))
    assert reader.request("repos/o/r/pulls/7") == {}
    assert timeouts == [2.0]
