"""The datasets the producer builds, pinned for the page's own decoders (MPA WP5a-B; CLAUDE.md rule 12).

The page's reader, ``frontend/features/analysis/lib/laterFilings.ts``, is the contract: it refuses any dataset whose
later-filing evidence it would print wrong. Rather than a copy of its rules here, the producer's datasets are committed
as ``backend/tests/fixtures/analysis_first_reports_produced.json`` and the page's decoders run on them:

- ``test_the_committed_datasets_are_what_the_producer_builds`` (here) fails when the producer's output for any pinned
  shape differs from the committed file, so the file is never stale;
- ``frontend/tests/unit/later-filings-producer.spec.ts`` runs every committed dataset through the real
  ``decodeLaterFilings`` and ``decodeDataNotes`` (each must be admitted unchanged) and holds REGN's
  ``laterFilingPlaces`` to the shared fixture's REGN case (``analysis_later_filings.json``).

So a producer change the page would refuse fails one of the two: the backend test until the file is regenerated, the
frontend spec once it is. Regenerate after a deliberate change, from ``backend/``:
``WP5A_REGENERATE_PRODUCED=1 python -m pytest tests/unit/test_first_reports_wire.py``, then run the frontend spec.

The shapes are WP5b's REGN sync (``test_companyfacts_own_report_history.py``) and three findings built on it: an exact
sign flip of FY2018 net income in the FY2020 10-K, the FY2018 balance in thousands in the FY2019 10-K, and FY2018
revenue in thousands in the FY2020 10-K (a finding on the net margin's input); each over FY2017..FY2021 and
FY2018..FY2021. A dataset is normalized where a build varies: the company (CIK, ticker, name), the sync time
(``data_as_of``) and the fingerprint, recomputed over the normalized dataset.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from tests.unit import test_first_reports as first_reports
from tests.unit.test_companyfacts_own_report_history import _REVENUE, _items, _payload
from tests.unit.test_first_reports import _build, _net_income, _synced

# test_first_reports' fixtures: its tables, and a session whose filing rows leave with the test.
_tables, db = first_reports._tables, first_reports.db

PRODUCED = Path(__file__).resolve().parents[1] / "fixtures" / "analysis_first_reports_produced.json"
CIK, TICKER, NAME = "872589", "REGN", "Regeneron Pharmaceuticals"


def _scale_assets():
    return _items({2017: {2016: 9_520.2e6, 2017: 11_734.5e6}, 2018: {2017: 11_734.5e6, 2018: 15_163.8e6},
                   2019: {2018: 15_163.8e3, 2019: 17_163.4e6}, 2020: {2019: 17_163.4e6, 2020: 19_994.1e6},
                   2021: {2020: 19_994.1e6, 2021: 25_434.7e6}}, instant=True)


SHAPES = {
    "regn": lambda: _payload(),
    "a-sign-flip": lambda: _payload(tags=_net_income({2018: -2_444.4e6})),
    "a-scale-factor": lambda: _payload(assets=_scale_assets()),
    "an-inputs-finding": lambda: _payload(_items({**_REVENUE, 2020: {**_REVENUE[2020], 2018: 6_710.8e3}})),
}
WINDOWS = (("FY2017", "FY2021"), ("FY2018", "FY2021"))


def _normalized(dataset, company):
    """The dataset as JSON, its company, sync time and fingerprint set where a build varies them."""
    from app.services.trend_analysis.dataset import dataset_fingerprint

    text = json.dumps(dataset, default=str).replace(f"/edgar/data/{company.cik}/", f"/edgar/data/{CIK}/")
    wire = json.loads(text)
    wire.update(ticker=TICKER, company_name=NAME, data_as_of=None)
    wire["snapshot_id"] = dataset_fingerprint(wire)
    return wire


def _produce(db):
    datasets = {}
    for shape, payload in SHAPES.items():
        company = _synced(db, payload())
        for start, end in WINDOWS:
            datasets[f"{shape} {start}..{end}"] = _normalized(_build(db, company, start, end), company)
    return datasets


def _write(datasets):
    """One dataset per line, so a change reads as the datasets it touches."""
    lines = ",\n".join(f"    {json.dumps(name)}: {json.dumps(datasets[name], sort_keys=True, separators=(',', ':'))}"
                       for name in datasets)
    description = ("The analysis datasets the WP5a-B producer (backend/app/services/trend_analysis/first_reports.py) "
                   "builds from WP5b's REGN sync and three findings on it, each over two windows; generated by "
                   "backend/tests/unit/test_first_reports_wire.py (its docstring says how to regenerate), held equal "
                   "to the producer's output there, and run through the page's decoders by "
                   "frontend/tests/unit/later-filings-producer.spec.ts.")
    PRODUCED.write_text("{\n  \"description\": " + json.dumps(description) + ",\n  \"datasets\": {\n" + lines + "\n  }\n}\n")


@pytest.mark.requires_db
def test_the_committed_datasets_are_what_the_producer_builds(db):
    datasets = _produce(db)
    if os.environ.get("WP5A_REGENERATE_PRODUCED") == "1":
        _write(datasets)
    committed = json.loads(PRODUCED.read_text())["datasets"]
    assert list(committed) == list(datasets)
    for name in datasets:
        assert committed[name] == datasets[name], f"{name}: regenerate the fixture (this module's docstring)"


def test_every_committed_dataset_carries_the_evidence_it_is_pinned_for():
    # A fixture with no evidence would let the page's spec pass on nothing.
    datasets = json.loads(PRODUCED.read_text())["datasets"]
    for name, dataset in datasets.items():
        points = [point for series in dataset["series"] for point in series["points"]]
        assert dataset["mode"] == "annual" and any("first_reported" in point for point in points), name
        assert any("yoy_first_reported" in point for point in points), name
    findings = {name for name, dataset in datasets.items() for series in dataset["series"] for point in series["points"]
                if (point.get("first_reported") or {}).get("disagreement")}
    assert {name.split(" ")[0] for name in findings} == {"a-sign-flip", "a-scale-factor", "an-inputs-finding"}
