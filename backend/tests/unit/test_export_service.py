def _closing_note(html: str) -> list[str]:
    """The PDF's closing note as it prints: the text of each <p> in the one closing-note footnote div,
    whitespace collapsed. A renamed class, a second note, or text outside a <p> fails here."""
    notes = re.findall(r'<div class="closing-note footnote">.*?</div>', html, re.DOTALL)
    assert len(notes) == 1, notes
    note = ET.fromstring(notes[0])
    assert len(note) and all(child.tag == "p" for child in note), notes[0]
    assert not "".join([note.text or "", *(child.tail or "" for child in note)]).strip(), notes[0]
    return [" ".join("".join(child.itertext()).split()) for child in note]


def _csv_rows(csv_text: str) -> list[list[str]]:
    return list(csv.reader(io.StringIO(csv_text.removeprefix("\ufeff"))))


