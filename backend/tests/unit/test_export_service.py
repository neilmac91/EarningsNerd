    @staticmethod
    def _alignment(html: str, first_header: str) -> list[tuple[str, bool, list[bool]]]:
        """The table headed by ``first_header``: each column's header, whether the header takes
        class="num" and whether each cell under it does."""
        for fragment in re.findall(r"<table>.*?</table>", html, re.DOTALL):
            table = ET.fromstring(fragment)
            heads = table.findall("./thead/tr/th")
            if heads and heads[0].text == first_header:
                rows = table.findall("./tbody/tr")
                return [(th.text, th.get("class") == "num", [row[c].get("class") == "num" for row in rows])
                        for c, th in enumerate(heads)]
        raise AssertionError(f"no table headed {first_header!r}")

    def test_numeric_columns_follow_the_pages_rule(self, service):
        """A PDF table aligns the columns the page does (F17; the review of 58fc49ce, finding 1).
        The metrics block is FinancialMetricsTable on the page, whose Current Period, Prior Period
        and Change are numeric by definition: each header and every cell under it takes
        class="num", "+14.4 ppts" and "—" among them. Any other table is GenericTable on the page:
        a column whose every non-empty cell is a whole figure (or the bare null token) takes
        class="num", and a figure followed by words stays prose, in a column headed "Change" too."""
        from app.services.export_service import numeric_columns

        rows = [
            ["Revenue", "$9.89B", "(12.4)", "+14.4 ppts", "41% operating margin", "", "61.2%"],
            ["Margin", "—", "-3.2%", "+2.2%", "$2.1B goodwill", "", "-"],
        ]
        assert numeric_columns(rows, 8) == [False, True, True, False, False, False, True, False]
        html = service.generate_pdf_html(*_make_summary_and_filing(_full_sections()))
        assert self._alignment(html, "Metric") == [
            ("Metric", False, [False, False]),
            ("Current Period", True, [True, True]),
            ("Prior Period", True, [True, True]),
            ("Change", True, [True, True]),  # "+2.2%" and "+14.4 ppts"
            ("Investor Takeaway", False, [False, False]),
        ]
        assert '<td class="num">+14.4 ppts</td>' in html
        assert self._alignment(html, "Segment") == [
            ("Segment", False, [False]), ("Revenue", True, [True]), ("Change", True, [True]), ("Commentary", False, [False]),
        ]
        # The header rule is the metrics block's alone, and it holds where a cell is the null token.
        segment = summary_sections.Block(
            "table", headers=["Segment", "Revenue", "Change", "Commentary"], rows=[["Cloud", "$4.1B", "+14.4 ppts", "Mature"]],
        )
        assert self._alignment(service._render_block_html(segment), "Segment")[2] == ("Change", False, [False])
        metrics = summary_sections.Block(
            "metrics", headers=["Metric", "Current Period", "Prior Period", "Change", "Investor Takeaway"],
            rows=[["Odd metric", "74.9%", "60.5", "—", "Mixed units."]],
        )
        assert [num for _, num, _ in self._alignment(service._render_block_html(metrics), "Metric")] == [
            False, True, True, True, False,
        ]

    def test_a_figure_cell_keeps_to_one_line(self, service):
        """The page never breaks a figure (FinancialMetricsTable's figure spans and GenericTable's
        numeric cells are nowrap), so a long takeaway beside "+14.4 ppts" leaves it on one line.
        A real WeasyPrint layout: every td.num lays out on exactly one line."""
        weasyprint = pytest.importorskip("weasyprint")
        from weasyprint.formatting_structure import boxes

        sections = _full_sections()
        for row in sections["financial_highlights"]["table"]:
            row["commentary"] = "A long investor takeaway that runs on for several clauses. " * 3
        html = service.generate_pdf_html(*_make_summary_and_filing(sections))
        try:
            document = weasyprint.HTML(string=html).render()
        except Exception as exc:  # missing system libs in odd envs: not what this test reads
            pytest.skip(f"WeasyPrint runtime unavailable: {exc}")
        lines = {
            "".join(box.element.itertext()): sum(isinstance(child, boxes.LineBox) for child in box.descendants())
            for page in document.pages for box in page._page_box.descendants()
            if isinstance(box, boxes.TableCellBox) and box.element is not None
            and box.element.tag == "td" and box.element.get("class") == "num"
        }
        assert "+14.4 ppts" in lines and "$9.89B" in lines, lines
        assert {text: count for text, count in lines.items() if count != 1} == {}


