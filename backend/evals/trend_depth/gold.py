"""Hand-written gold analyses: search the filings, check a draft against the gate, list its causal sources.

    cd backend && python -m evals.trend_depth.gold find REGN "EYLEA HD.{0,80}increased"
    cd backend && python -m evals.trend_depth.gold check REGN
    cd backend && python -m evals.trend_depth.gold causes REGN SNAP JPM

A gold analysis is ``tasks/analysis-depth-2026-10/gold/<TICKER>.md``: ``## Section`` headings, each sentence
ending in its type tag (``{fact}``, ``{comparison}``, ``{cause}``, ``{judgement}``) after its citations. It
cites the company's evidence pack (``packs/<TICKER>.json.gz``). A passage the pack did not select may be
added in ``gold/<TICKER>.passages.json`` with an ID ``Q<n>`` and its EDGAR location (``find`` prints
both); how many a writer needed is a measure of the pack's passage recall.
"""
from __future__ import annotations

import json
import re
import sys
from typing import Any

from evals.trend_depth import bootstrap, factcheck, passages
from evals.trend_depth.generate import RUNS, load_pack

GOLD = bootstrap.RECORDS / "gold"


def pack_with_extras(ticker: str) -> dict[str, Any]:
    pack = load_pack(ticker)
    extra_path = GOLD / f"{ticker}.passages.json"
    if extra_path.exists():
        pack = {**pack, "passages": pack["passages"] + json.loads(extra_path.read_text())}
    return pack


def find(ticker: str, pattern: str, limit: int = 20) -> None:
    pack = load_pack(ticker)
    regex = re.compile(pattern, re.IGNORECASE | re.DOTALL)
    shown = 0
    for filing in pack["filings"]:
        parsed = bootstrap.read_cached(f"documents/{filing['accession']}.json")
        if not parsed:
            continue
        found_in_mda = False
        for basis in ("mda", "full"):
            if basis == "full" and found_in_mda:
                break  # a match in this filing's MD&A is enough; skip the same paragraph in the full text
            text = parsed.get(basis) or ""
            for offset, block in passages._paragraphs(text):
                if not regex.search(block):
                    continue
                print(json.dumps({
                    "fiscal_year": filing["period"], "accession": filing["accession"], "form": "10-K",
                    "basis": basis, "offset": offset, "document_url": filing["document_url"],
                    "url": passages.fragment_url(filing["document_url"], block[:1100]), "text": block[:1100],
                }))
                shown += 1
                found_in_mda = found_in_mda or basis == "mda"
                if shown >= limit:
                    return


def check(ticker: str) -> dict[str, Any]:
    pack = pack_with_extras(ticker)
    sentences = factcheck.sentences_from_markdown((GOLD / f"{ticker}.md").read_text())
    result = factcheck.check(sentences, pack)
    untyped = [s["text"][:80] for s in sentences if s["type"] == "untyped"]
    words = sum(len(factcheck.CITATION_RE.sub("", s["text"]).split()) for s in sentences)
    print(f"{ticker}: passed={result['passed']} sentences={result['sentences']} types={result['sentence_types']} "
          f"claims={result['claims']} verified={result['verified']} counts={result['unverified_counts']} words={words}")
    for failure in result["failures"]:
        print(f"  FAIL [{failure['section']}] {failure['failure']}\n       {failure['sentence'][:220]}")
    for text in untyped:
        print(f"  UNTYPED {text}")
    return result


def causes(tickers: list[str], audit_label: str = "") -> str:
    """Every gold cause sentence with each passage it cites. With ``audit_label``, also the label the
    causal-support auditor gave the sentence in ``runs/<audit_label>/causes/gold/``."""
    lines = ["# Causal claims in the gold examples and the EDGAR passages they rest on", "",
             "Generated by `python -m evals.trend_depth.gold causes`. Each row is one cause sentence and one "
             "passage it cites; the link opens the 10-K at the passage (text fragment)."
             + (f" The audit column is the label a model from another family gave the sentence after reading the "
                f"passages (`causes.py`, run `{audit_label}`)." if audit_label else ""), ""]
    for ticker in tickers:
        pack = pack_with_extras(ticker)
        by_id = {p["id"]: p for p in pack["passages"]}
        sentences = factcheck.sentences_from_markdown((GOLD / f"{ticker}.md").read_text())
        audit: dict[str, str] = {}
        audit_path = RUNS / audit_label / "causes" / "gold" / f"{ticker}.json"
        if audit_label and audit_path.exists():
            record = json.loads(audit_path.read_text())
            audit = {i["sentence"]: f"{i['label']} ({record.get('auditor')}): {i['reason']}" for i in record.get("items", [])}
        lines += [f"## {ticker}", "", "| # | Causal claim | Passage | Filing and location | Quoted text |" + (" Audit |" if audit_label else ""),
                  "|---|---|---|---|---|" + ("---|" if audit_label else "")]
        n = 0
        for sentence in sentences:
            if sentence["type"] != "cause":
                continue
            refs = [r for g in factcheck.CITATION_RE.findall(sentence["text"]) for r in factcheck.ID_RE.findall(g)]
            for ref in refs:
                passage = by_id.get(ref)
                if not passage:
                    continue
                n += 1
                claim = factcheck.CITATION_RE.sub("", sentence["text"]).strip().replace("|", "\\|")
                where = f"{passage['fiscal_year']} 10-K, accession {passage['accession']}, {passage.get('section', '')}"
                if passage.get("heading"):
                    where += f" › {passage['heading']}"
                quote = passage["text"].replace("|", "\\|")
                quote = quote if len(quote) <= 420 else quote[:420].rsplit(" ", 1)[0] + " …"
                row = f"| {n} | {claim} | {ref} | [{where}]({passage['url']}) | “{quote}” |"
                if audit_label:
                    row += f" {audit.get(claim, 'not audited').replace('|', '/')} |"
                lines.append(row)
        lines.append("")
    text = "\n".join(lines)
    (GOLD / "CAUSES.md").write_text(text)
    return text


def remap(ticker: str, old_pack_path: str) -> None:
    """Rewrite a gold file's citations after the pack is rebuilt: values move by (series key, period),
    passages by (accession, opening text), red flags by kind. An ID with no counterpart is reported, not
    guessed; the gate then rechecks every number against the new pack."""
    old = json.loads(open(old_pack_path).read())
    new = load_pack(ticker)
    old_keys = {vid: key for key, vid in old["series_keys"].items()}
    passages_new = {(p["accession"], p["text"][:120]): p["id"] for p in new["passages"]}
    flags_new = {f["detail"].split(":")[0][:60]: f["id"] for f in new["red_flags"]}
    mapping: dict[str, str] = {}
    for vid in old["values"]:
        key = old_keys.get(vid)
        if key and key in new["series_keys"]:
            mapping[vid] = new["series_keys"][key]
    for passage in old["passages"]:
        target = passages_new.get((passage["accession"], passage["text"][:120]))
        if target:
            mapping[passage["id"]] = target
    for flag in old["red_flags"]:
        target = flags_new.get(flag["detail"].split(":")[0][:60])
        if target:
            mapping[flag["id"]] = target
    path = GOLD / f"{ticker}.md"
    text = path.read_text()
    missing = sorted({ref for group in factcheck.CITATION_RE.findall(text) for ref in factcheck.ID_RE.findall(group)
                      if not ref.startswith("Q") and ref not in mapping})

    def swap(match: re.Match[str]) -> str:
        refs = factcheck.ID_RE.findall(match.group(1))
        return "".join(f"[{mapping.get(ref, ref)}]" for ref in refs)

    path.write_text(factcheck.CITATION_RE.sub(swap, text))
    print(f"{ticker}: remapped; unmapped IDs: {missing or 'none'}")


def main() -> None:
    command, *args = sys.argv[1:]
    if command == "remap":
        remap(args[0], args[1])
        return
    if command == "find":
        find(args[0], args[1], int(args[2]) if len(args) > 2 else 20)
    elif command == "check":
        for ticker in args:
            check(ticker)
    elif command == "causes":
        audit_label = args[args.index("--audit") + 1] if "--audit" in args else ""
        causes([a for a in args if a != "--audit" and a != audit_label], audit_label)
        print(f"wrote {GOLD / 'CAUSES.md'}")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
